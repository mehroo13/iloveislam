#!/usr/bin/env python3
"""Generate the Madani mushaf page mapping for the Hifz app (2026-11-21).

Reads the live Quran.com chapters API (saved to /tmp/chapters.json) and
fetches the first verse of each juz (verses/by_juz/{n}?per_page=1, which
carries the verse's mushaf page_number), and emits:
  - app/hifz/mushaf.ts — surah -> first/last mushaf page, juz -> first page

The Madani mushaf has 604 pages. Quran.com's `pages` field per chapter is
the authoritative page range for each surah in that mushaf.

Usage:
  curl -s "https://api.quran.com/api/v4/chapters" -o /tmp/chapters.json
  python3 tools/gen_mushaf.py
"""
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHAPTERS_JSON = Path('/tmp/chapters.json')
OUT = ROOT / 'app' / 'hifz' / 'mushaf.ts'

TOTAL_PAGES = 604


def fetch_json(url: str) -> dict:
    req = urllib.request.Request(
        url,
        headers={
            'Accept': 'application/json',
            'User-Agent': 'Mozilla/5.0 (compatible; iloveislam-life/1.0)',
        },
    )
    with urllib.request.urlopen(req, timeout=25) as res:
        return json.loads(res.read().decode('utf-8'))


def main() -> int:
    if not CHAPTERS_JSON.exists():
        print('missing /tmp/chapters.json — fetch it first (see usage)', file=sys.stderr)
        return 1
    chapters = json.load(open(CHAPTERS_JSON))['chapters']
    assert len(chapters) == 114, f"expected 114 chapters, got {len(chapters)}"

    surah_pages = {}
    for c in sorted(chapters, key=lambda x: x['id']):
        pages = c.get('pages')
        assert pages and len(pages) == 2, f"chapter {c['id']} has no pages range"
        surah_pages[c['id']] = (int(pages[0]), int(pages[1]))
    assert surah_pages[1] == (1, 1), surah_pages[1]
    assert surah_pages[114][1] == 604, surah_pages[114]

    # Juz first pages: first verse of each juz carries its mushaf page.
    juz_first_page = {}
    for n in range(1, 31):
        d = fetch_json(
            f'https://api.quran.com/api/v4/verses/by_juz/{n}'
            '?per_page=1&fields=text_uthmani'
        )
        verses = d.get('verses', [])
        assert verses, f'juz {n}: no verses returned'
        page = int(verses[0]['page_number'])
        juz_first_page[n] = page
    # Sanity: juz first pages strictly increase, starting at 1.
    pages_sorted = [juz_first_page[n] for n in range(1, 31)]
    assert pages_sorted[0] == 1, pages_sorted
    assert all(b > a for a, b in zip(pages_sorted, pages_sorted[1:])), pages_sorted

    lines = []
    lines.append('// app/hifz/mushaf.ts — Madani mushaf (604-page) mapping.')
    lines.append('// Generated by tools/gen_mushaf.py from the live Quran.com')
    lines.append('// chapters API (`pages` per chapter) and the first verse of')
    lines.append('// each juz (its mushaf page_number) — do not hand-edit;')
    lines.append('// re-run the script instead. Verified live 2026-11-21.')
    lines.append('')
    lines.append('/** Total pages in the Madani mushaf. */')
    lines.append(f'export const MUSHAF_TOTAL_PAGES = {TOTAL_PAGES};')
    lines.append('')
    lines.append('/** First mushaf page of each surah, by surah id (1–114). */')
    lines.append('export const SURAH_FIRST_PAGE: Record<number, number> = {')
    for sid in sorted(surah_pages):
        lines.append(f'  {sid}: {surah_pages[sid][0]},')
    lines.append('};')
    lines.append('')
    lines.append('/** Last mushaf page of each surah, by surah id (1–114). */')
    lines.append('export const SURAH_LAST_PAGE: Record<number, number> = {')
    for sid in sorted(surah_pages):
        lines.append(f'  {sid}: {surah_pages[sid][1]},')
    lines.append('};')
    lines.append('')
    lines.append('/** First mushaf page of each juz, by juz number (1–30). */')
    lines.append('export const JUZ_FIRST_PAGE: Record<number, number> = {')
    for n in range(1, 31):
        lines.append(f'  {n}: {juz_first_page[n]},')
    lines.append('};')
    lines.append('')
    lines.append('/** Surah ids that appear on a mushaf page (usually 1, sometimes 2). */')
    lines.append('export function surahsOnMushafPage(page: number): number[] {')
    lines.append('  const ids: number[] = [];')
    lines.append('  for (let id = 1; id <= 114; id++) {')
    lines.append('    if (page >= SURAH_FIRST_PAGE[id] && page <= SURAH_LAST_PAGE[id]) ids.push(id);')
    lines.append('  }')
    lines.append('  return ids;')
    lines.append('}')
    lines.append('')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'wrote {OUT}: 114 surah ranges, 30 juz first pages')
    print('juz first pages:', pages_sorted)
    return 0


if __name__ == '__main__':
    sys.exit(main())
